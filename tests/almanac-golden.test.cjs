"use strict";
/* Golden check of the almanac against an independent reference
   (tests/fixtures/almanac-golden.json, generated by
   scripts/almanac-golden.py from cnlunar — see that script for the
   licence note and field definitions). The reference reckons in Beijing
   time, so this file pins the zone BEFORE any Date is built: it is
   deterministic on any machine. Each test file runs in its own process
   under `node --test`, so the pin does not leak into other suites. */
process.env.TZ = "Asia/Shanghai";

const test = require("node:test");
const assert = require("node:assert/strict");
const fixture = require("./fixtures/almanac-golden.json");
const { harness } = require("./almanac-harness.cjs");

const { api, surface } = harness();
const at = (iso) => {
  const [y, m, d] = iso.split("-").map(Number);
  return new Date(y, m - 1, d, 12, 0);
};
const rows = fixture.rows.map((r) => Object.fromEntries(fixture.fields.map((k, i) => [k, r[i]])));

/* Where the reference and our engine are KNOWN to differ, and why.
   lunarYear comes from the browser's Intl chinese calendar (ICU). The
   new moon of 2027-02-06 is at 15:56 UTC = 23:56 Beijing time, so
   正月初一 of 丁未 is Feb 6 (cnlunar, and the official calendar). ICU
   78's lower-precision lunar model puts the conjunction after midnight
   and starts the year on Feb 7. Either value is accepted so a fixed ICU
   does not break the test; any OTHER deviation fails. See
   docs/almanac-rules.md. */
const KNOWN_ICU_DEVIATIONS = {
  "2027-02-06": { lunarYear: "丙午" },
};

test("golden fixture covers every day of 2025–2028, Beijing time", () => {
  assert.equal(fixture.timeZone, "Asia/Shanghai");
  assert.equal(rows.length, 365 + 365 + 365 + 366);
  assert.equal(new Date(2026, 0, 1).getTimezoneOffset(), -480, "TZ pinned before any Date use");
  // Both leap months are inside the window.
  assert.ok(rows.some((r) => r.lunar.startsWith("L6-")), "2025 闰六月");
  assert.ok(rows.some((r) => r.lunar.startsWith("L5-")), "2028 闰五月");
});

for (const year of [2025, 2026, 2027, 2028]) {
  test(`almanac matches the golden reference day by day — ${year}`, () => {
    const misses = [];
    for (const r of rows.filter((x) => x.date.startsWith(String(year)))) {
      const a = api.computeAlmanac(at(r.date));
      const ours = {
        lunarYear: a.yearGanzhi,
        lichunYear: a.lichunYearGanzhi,
        month: a.monthGanzhi,
        day: a.dayGanzhi,
        jianchu: a.jianchu,
        chong: a.chong,
        sha: a.sha,
        term: a.termInfo.today ? a.termInfo.today.name : "",
      };
      for (const [k, v] of Object.entries(ours)) {
        if (v === r[k]) continue;
        const known = KNOWN_ICU_DEVIATIONS[r.date];
        if (known && known[k] === v) continue;
        misses.push(`${r.date} ${k}: ours ${v}, reference ${r[k]}`);
      }
      assert.equal(a.chongSha, `冲${r.chong}煞${r.sha}`);
      assert.equal(a.jieMonth.branch, r.month[1], `${r.date} 节月 branch`);
    }
    assert.deepEqual(misses, []);
  });
}

test("worked example: 2026-01-01 … 2026-02-16 is still 乙巳年 (Spring Festival Feb 17)", () => {
  for (const iso of ["2026-01-01", "2026-02-04", "2026-02-16"]) {
    assert.equal(api.computeAlmanac(at(iso)).yearGanzhi, "乙巳", iso);
  }
  assert.equal(api.computeAlmanac(at("2026-02-17")).yearGanzhi, "丙午");
  // The 立春-based year turns earlier, at 立春 (2026-02-04).
  assert.equal(api.lichunYearGanzhi(at("2026-02-03")), "乙巳");
  assert.equal(api.lichunYearGanzhi(at("2026-02-04")), "丙午");
  const s = surface();
  api.renderSelection({ cat: "almanac", data: api.computeAlmanac(at("2026-01-15")) }, s);
  assert.ok(s.meta.textContent.includes("乙巳年") || s.meta.innerHTML.includes("乙巳年"), "card names 乙巳年");
});

test("worked example: 大雪 day 2026-12-07 乙卯 repeats 平 (交节 day)", () => {
  const before = api.computeAlmanac(at("2026-12-06"));
  const on = api.computeAlmanac(at("2026-12-07"));
  assert.equal(before.dayGanzhi, "甲寅");
  assert.equal(before.jianchu, "平");
  assert.equal(on.dayGanzhi, "乙卯");
  assert.equal(on.jianchu, "平");
  assert.equal(on.termInfo.today.name, "大雪");
  const jm = api.jieMonthInfo(at("2026-12-07"));
  assert.equal(jm.branch, "子");
  assert.equal(jm.termName, "大雪");
  assert.equal(jm.today, true);
  assert.equal(api.jieMonthInfo(at("2026-12-06")).branch, "亥");
});

test("worked example: 2027-02-05 乙卯 is 除 (立春 2027-02-04 opens 寅月)", () => {
  const a = api.computeAlmanac(at("2027-02-05"));
  assert.equal(a.dayGanzhi, "乙卯");
  assert.equal(a.jianchu, "除");
  assert.equal(api.computeAlmanac(at("2027-02-04")).jianchu, "建");
  const jm = api.jieMonthInfo(at("2027-02-05"));
  assert.deepEqual([jm.branch, jm.monthIdx, jm.jieYear, jm.termName], ["寅", 0, 2027, "立春"]);
  assert.equal(api.jieMonthGanzhi(at("2027-02-05")), "壬寅"); // 丁壬壬位顺行流
});

test("worked example: 2026-11-24 壬寅 → 冲猴煞北", () => {
  const a = api.computeAlmanac(at("2026-11-24"));
  assert.equal(a.dayGanzhi, "壬寅");
  assert.equal(a.chongSha, "冲猴煞北");
  const s = surface();
  api.renderSelection({ cat: "almanac", data: a }, s);
  assert.ok(s.body.innerHTML.includes("冲猴煞北"));
});
