#!/usr/bin/env node
/* Download a published Sky Engine release into vendor/sky-engine/<version>/.
   Does not edit the generated bytes. After it runs, point the adapter,
   service worker and docs at the new directory and bump nam-vN together.
   Usage: node scripts/update-sky-engine.mjs sky-engine-v0.2.0
*/
import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const tag = process.argv[2] || "sky-engine-v0.2.0";
if (!/^sky-engine-v\d+\.\d+\.\d+$/.test(tag)) {
  console.error("Expected a tag like sky-engine-v0.2.0");
  process.exit(1);
}
const version = tag.slice("sky-engine-v".length);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dest = path.join(root, "vendor", "sky-engine", version);
const base = `https://github.com/mingzhangyang/elsewhere/releases/download/${tag}/`;
const names = ["SHA256SUMS", "manifest.json", "sky-engine.mjs", "stars.json", "sky-engine-NOTICES.txt"];

await mkdir(dest, { recursive: true });
const files = new Map();
for (const name of names) {
  const res = await fetch(base + name);
  if (!res.ok) throw new Error(`${name} HTTP ${res.status}`);
  files.set(name, Buffer.from(await res.arrayBuffer()));
}
const sums = files.get("SHA256SUMS").toString("utf8").trim().split(/\n/);
const expected = new Map();
for (const line of sums) {
  const match = /^([a-f0-9]{64})\s+(\S+)$/.exec(line.trim());
  if (!match) throw new Error("Bad SHA256SUMS line: " + line);
  expected.set(match[2], match[1]);
}
for (const name of names) {
  if (name === "SHA256SUMS") continue;
  const hash = createHash("sha256").update(files.get(name)).digest("hex");
  if (expected.get(name) !== hash) {
    throw new Error(`${name} sha256 ${hash} != published ${expected.get(name)}`);
  }
}
if (expected.has("moon-lroc.jpg") && !files.has("moon-lroc.jpg")) {
  const res = await fetch(base + "moon-lroc.jpg");
  if (!res.ok) throw new Error(`moon-lroc.jpg HTTP ${res.status}`);
  const buf = Buffer.from(await res.arrayBuffer());
  const hash = createHash("sha256").update(buf).digest("hex");
  if (expected.get("moon-lroc.jpg") !== hash) {
    throw new Error(`moon-lroc.jpg sha256 ${hash} != published ${expected.get("moon-lroc.jpg")}`);
  }
  files.set("moon-lroc.jpg", buf);
}
const manifest = JSON.parse(files.get("manifest.json").toString("utf8"));
if (manifest.version !== version || manifest.tag !== tag) {
  throw new Error(`manifest ${manifest.version} / ${manifest.tag} does not match ${tag}`);
}
for (const [name, buf] of files) await writeFile(path.join(dest, name), buf);
const notice = await readFile(path.join(dest, "manifest.json"), "utf8");
console.log(`Vendored ${tag} at vendor/sky-engine/${version}/`);
console.log(`sourceCommit ${manifest.sourceCommit}`);
console.log("Next: point js/sky-engine-adapter.js and sw.js at this directory,");
console.log("bump the nam-vN cache and every ?v=N, then run node --test tests/*.test.cjs.");
console.log("Do not hand-edit sky-engine.mjs or stars.json. Rollback is the previous directory.");
void notice;
